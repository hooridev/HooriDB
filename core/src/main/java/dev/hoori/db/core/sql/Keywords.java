  private static final Set<String> OFFERED_MARIADB =
      union(RESERVED_MARIADB, TYPED, TYPED_MYSQL, Set.of("SEQUENCE"));
  private static final Set<String> OFFERED_MYSQL = union(RESERVED_MYSQL, TYPED, TYPED_MYSQL);

  /** The words the provider's server reserves. */
  public static Set<String> reserved(Provider provider) {
    return switch (provider) {
      case POSTGRESQL -> RESERVED_POSTGRESQL;
      case MARIADB -> RESERVED_MARIADB;
      case MYSQL -> RESERVED_MYSQL;
    };
  }

  /** The words completion offers on the provider's server. */
  public static Set<String> offered(Provider provider) {
    return switch (provider) {
      case POSTGRESQL -> OFFERED_POSTGRESQL;
      case MARIADB -> OFFERED_MARIADB;
      case MYSQL -> OFFERED_MYSQL;
    };
  }

  /** Whether the word, in any case, is reserved on the provider's server. */
  public static boolean isReserved(String word, Provider provider) {
    return reserved(provider).contains(word.toUpperCase(Locale.ROOT));
  }

  private static Set<String> words(String text) {
    return Set.of(text.strip().split("\\s+"));
  }

  @SafeVarargs
  private static Set<String> union(Set<String>... sets) {
    var all = new HashSet<String>();
    for (var set : sets) {
      all.addAll(set);
    }
    return Set.copyOf(all);
  }
